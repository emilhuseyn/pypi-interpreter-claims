r"""Write v2/draft/bibliography.tex from v2/research/references.json, numbered in order of first
citation in the manuscript (AMA-like: up to six authors, else three and et al.; DOI on every DOI
entry). Page ranges keep a plain hyphen; nothing here can produce an en dash.

    py v2/scripts/36_bib.py
"""
import io
import json
import os
import re
import sys

sys.stdout.reconfigure(encoding="utf-8")
V2 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(V2, "draft")


def tex_escape(s):
    s = s.replace("\u2010", "-").replace("\u2011", "-").replace("\u2013", "-").replace("\u2014", "-")
    s = re.sub(r"<[^>]+>", "", s)
    for a, b in (("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#")):
        s = s.replace(a, b)
    return s


def initials(given):
    return "".join(p[0] for p in re.split(r"[\s\-.]+", given) if p)


def authors(lst):
    names = ["%s %s" % (tex_escape(f.title() if f.isupper() else f), initials(g)) for g, f in lst]
    return ", ".join(names if len(names) <= 6 else names[:3] + ["et al"])


def order():
    tex = io.open(os.path.join(D, "manuscript.tex"), encoding="utf-8").read()
    for m in re.finditer(r"\\input\{([^}]+)\}", tex):
        p = os.path.join(D, m.group(1) + ".tex")
        if os.path.exists(p) and m.group(1) not in ("numbers", "bibliography"):
            tex = tex.replace(m.group(0), io.open(p, encoding="utf-8").read())
    tex = re.sub(r"(?m)%.*$", "", tex)
    out = []
    for m in re.finditer(r"\\cite\{([^}]*)\}", tex[tex.index("\\begin{document}"):]):
        for k in m.group(1).split(","):
            if k.strip() not in out:
                out.append(k.strip())
    return out


def main():
    refs = json.load(io.open(os.path.join(V2, "research", "references.json"), encoding="utf-8"))
    items = []
    for k in order():
        if k in refs["doi"]:
            r = refs["doi"][k]
            src = tex_escape(r["container"])
            if r["type"] == "journal-article":
                loc = "%s. %s" % (src, r["year"])
                if r.get("volume"):
                    loc += ";%s" % r["volume"]
                    if r.get("issue"):
                        loc += "(%s)" % r["issue"]
                if r.get("page") or r.get("article"):
                    loc += ":%s" % (r.get("page") or r.get("article")).replace("\u2013", "-")
            else:
                loc = "In: %s. %s" % (src, r["year"])
                if r.get("page"):
                    loc += ":%s" % r["page"].replace("\u2013", "-")
            items.append("\\bibitem{%s} %s. %s. %s. \\url{https://doi.org/%s}"
                         % (k, authors(r["crossref_authors"]), tex_escape(r["title"]), loc, r["doi"]))
        else:
            title, auth, year, url = refs["web"][k]
            items.append("\\bibitem{%s} %s. %s. %s. \\url{%s}. Accessed 14 November 2026."
                         % (k, tex_escape(auth), tex_escape(title), year, url))
    io.open(os.path.join(D, "bibliography.tex"), "w", encoding="utf-8").write(
        "%% generated by v2/scripts/36_bib.py; do not edit\n\\begin{thebibliography}{99}\n"
        + "\n\n".join(items) + "\n\\end{thebibliography}\n")
    print("%d references written in citation order" % len(items))


main()
